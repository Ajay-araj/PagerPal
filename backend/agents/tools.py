class IncidentToolExecutor:
    """Executes allowlisted read-only diagnostic tools against a SimulationRun."""

    # Maps topology short-IDs to the full service names used in metric/log keys
    _SVC_ALIASES: Dict[str, List[str]] = {
        "gateway":   ["gateway", "api-gateway"],
        "checkout":  ["checkout", "checkout-svc"],
        "payments":  ["payments", "payments-svc"],
        "inventory": ["inventory", "inventory-svc"],
        "auth":      ["auth", "auth-svc"],
        "orders-db": ["orders-db", "ordersdb"],
        "cache":     ["cache", "cache-svc"],
    }

    def __init__(self, run: SimulationRun):
        self.run = run

    def _resolve_service_names(self, service: str) -> List[str]:
        """Return all known name variants for a service ID."""
        s = service.lower().strip()
        # Build reverse map from any variant to canonical set
        for key, variants in self._SVC_ALIASES.items():
            if s == key or s in variants:
                return variants
        # Fallback: service itself + with/without -svc suffix
        base = s.removesuffix("-svc")
        return [s, f"{s}-svc", base]

    def execute(self, tool_name: str, args: Dict[str, Any]) -> Dict[str, Any]:
        service = args.get("service")
        if not service:
            return {"error": "Missing required parameter 'service'"}

        if tool_name == "get_pod_logs":
            limit = int(args.get("limit", 30))
            return self.get_pod_logs(service, limit)
        elif tool_name == "get_service_metrics":
            return self.get_service_metrics(service)
        elif tool_name == "get_trace_spans":
            limit = int(args.get("limit", 20))
            return self.get_trace_spans(service, limit)
        elif tool_name == "get_deploy_history":
            return self.get_deploy_history(service)
        elif tool_name == "check_health_probes":
            return self.check_health_probes(service)
        else:
            return {"error": f"Tool '{tool_name}' is not in the allowlist"}

    def get_pod_logs(self, service: str, limit: int = 30) -> Dict[str, Any]:
        variants = self._resolve_service_names(service)
        logs = [l for l in self.run.logs if l.service.lower() in variants]
        logs = logs[-limit:]
        sanitized_logs = []
        for l in logs:
            sanitized_msg = quarantine_untrusted_input(l.message).sanitized_text
            sanitized_logs.append({
                "timestamp": l.timestamp,
                "level": l.level,
                "service": l.service,
                "message": sanitized_msg,
                "trace_id": l.trace_id
            })
        return {
            "service": service,
            "log_count": len(sanitized_logs),
            "logs": sanitized_logs
        }

    def get_service_metrics(self, service: str) -> Dict[str, Any]:
        variants = self._resolve_service_names(service)
        series_data: Dict[str, Any] = {}
        for key, points in self.run.metrics.items():
            s_name = key.split(":", 1)[0].lower()
            if s_name in variants:
                metric_name = key.split(":", 1)[1]
                series_data[metric_name] = {
                    "unit": points[0].unit if points else "",
                    "points": [{"t": pt.timestamp, "v": pt.value} for pt in points[-10:]],
                    "latest_value": points[-1].value if points else None
                }
        return {
            "service": service,
            "metrics": series_data
        }

    def get_trace_spans(self, service: str, limit: int = 20) -> Dict[str, Any]:
        variants = self._resolve_service_names(service)
        spans = [s for s in self.run.traces if s.service.lower() in variants]
        spans = spans[-limit:]
        return {
            "service": service,
            "span_count": len(spans),
            "spans": [
                {
                    "trace_id": s.trace_id,
                    "span_id": s.span_id,
                    "operation": s.operation,
                    "service": s.service,
                    "duration_ms": s.duration_ms,
                    "status_code": s.status_code,
                    "error": s.error,
                    "error_message": quarantine_untrusted_input(s.error_message or "").sanitized_text if s.error_message else None
                }
                for s in spans
            ]
        }

    def get_deploy_history(self, service: str) -> Dict[str, Any]:
        variants = self._resolve_service_names(service)
        deploys = [d for d in self.run.deployments if d.service.lower() in variants]
        return {
            "service": service,
            "deployments": [
                {
                    "deploy_id": d.deploy_id,
                    "version": d.version,
                    "deployed_at": d.deployed_at,
                    "commit_sha": d.commit_sha,
                    "commit_message": d.commit_message,
                    "author": d.author,
                    "diff_summary": d.diff_summary
                }
                for d in deploys
            ]
        }

    def check_health_probes(self, service: str) -> Dict[str, Any]:
        metrics = self.get_service_metrics(service).get("metrics", {})
        err_data = metrics.get("error_rate_pct", {})
        lat_data = metrics.get("p95_latency_ms", {})

        latest_err = err_data.get("latest_value", 0.0) or 0.0
        latest_lat = lat_data.get("latest_value", 10.0) or 10.0

        is_healthy = latest_err < 1.0 and latest_lat < 300.0
        return {
            "service": service,
            "probe_endpoint": "/healthz",
            "status": "PASS" if is_healthy else "FAIL",
            "http_status": 200 if is_healthy else 503,
            "response_time_ms": round(latest_lat, 1),
            "error_rate_pct": round(latest_err, 2)
        }
